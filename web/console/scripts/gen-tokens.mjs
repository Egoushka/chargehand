// Generates src/styles/tokens.css from design/tokens.json, the design system's token file. The copy is verbatim except one sample
// string in the type section (a project name of the designer's), which is neutral here because the repository is public.
//
//   node scripts/gen-tokens.mjs           write src/styles/tokens.css
//   node scripts/gen-tokens.mjs --check   fail when the file on disk differs from what the tokens produce
//
// Dark is the default theme (`:root`, `[data-theme="dark"]`). Light is `[data-theme="light"]`, and also applies to a browser that
// asks for it (prefers-color-scheme: light) while no data-theme is set. Every colour is a custom property named as in the token file;
// a role token that points at a ramp step (`{neutral-1}`) becomes `var(--neutral-1)`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
export const TOKENS_JSON = here('../design/tokens.json');
export const TOKENS_CSS = here('../src/styles/tokens.css');

const reference = /^\{([\w-]+)\}$/;
const resolve = (value) => value.replace(reference, 'var(--$1)');
const line = (name, value) => `  --${name}: ${value};`;

/** The CSS text for a token file already parsed. */
export function generate(tokens) {
  const themed = (theme) => [
    `  color-scheme: ${theme};`,
    ...tokens.color.tokens.map((t) => line(t.name, resolve(t.value[theme]))),
    ...tokens.shadow.tokens.map((t) => line(t.name, t.value[theme])),
  ];
  const light = themed('light');
  const plain = (group) => group.tokens.map((t) => line(t.name, t.value));
  const fonts = Object.entries(tokens.type.families).map(([name, stack]) =>
    line(`font-${name}`, stack),
  );

  return [
    '/* Generated by scripts/gen-tokens.mjs from design/tokens.json: edit neither by hand (npm run tokens). */',
    ':root,',
    '[data-theme="dark"] {',
    ...themed('dark'),
    '}',
    '[data-theme="light"] {',
    ...light,
    '}',
    '@media (prefers-color-scheme: light) {',
    '  :root:not([data-theme]) {',
    ...light.map((l) => `  ${l}`),
    '  }',
    '}',
    ':root {',
    ...[tokens.spacing, tokens.radius, tokens.size, tokens.duration, tokens.zIndex].flatMap(plain),
    ...fonts,
    '}',
    '',
  ].join('\n');
}

/** The CSS for the committed token file. */
export const build = () => generate(JSON.parse(readFileSync(TOKENS_JSON, 'utf8')));

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const css = build();
  if (process.argv.includes('--check')) {
    if (readFileSync(TOKENS_CSS, 'utf8') !== css) {
      console.error('src/styles/tokens.css is out of date: run `npm run tokens`.');
      process.exit(1);
    }
    console.log('tokens.css matches design/tokens.json');
  } else {
    writeFileSync(TOKENS_CSS, css);
    console.log(`wrote src/styles/tokens.css (${css.split('\n').length - 1} lines)`);
  }
}
